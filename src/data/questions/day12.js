export function buildDay12Questions(domainKey) {
  const d = shared[domainKey];

  return [
    {
      id: "q31",
      title: `Connect ${d.transactionTable} to Their ${d.locationTable}`,
      topic: "JOIN · ON",
      prompt: `Return each ${d.plannedStatus} ${d.transactionLabel} with its ${d.transactionId}, ${d.locationLabel} name, and ${d.amount}. Determine which columns connect ${d.transactionTable} and ${d.locationTable}.`,
      starterSql: `-- Question 31: Connect ${d.transactionTable} to ${d.locationTable}\n\n`,
      solutionSql: `SELECT t.${d.transactionId},\n       l.${d.locationName} AS ${d.locationLabel},\n       t.${d.amount}\nFROM ${d.transactionTable} AS t\nJOIN ${d.locationTable} AS l\n  ON t.${d.transactionLocationId} = l.${d.locationId}\nWHERE t.${d.status} = '${d.plannedStatus}'\nORDER BY t.${d.transactionId};`,
    },

    {
      id: "q32",
      title: "Use Aliases to Make the Join Readable",
      topic: "ALIASES · QUALIFIED NAMES",
      prompt: `Join ${d.transactionTable} to ${d.locationTable} using aliases t and l. Return only ${d.transactionId}, the ${d.locationLabel} name, and ${d.status}, using qualified column names.`,
      starterSql: `-- Question 32: Use table aliases and qualified names\n\n`,
      solutionSql: `SELECT t.${d.transactionId},\n       l.${d.locationName} AS ${d.locationLabel},\n       t.${d.status}\nFROM ${d.transactionTable} AS t\nJOIN ${d.locationTable} AS l\n  ON t.${d.transactionLocationId} = l.${d.locationId}\nORDER BY t.${d.transactionId};`,
    },

    {
      id: "q33",
      title: "Filter the Joined Result",
      topic: "JOIN · WHERE",
      prompt: `Find ${d.transactionTable} going to ${d.locationTable} rows with ${d.locationCapacity} greater than ${d.capacityThreshold}. Return ${d.transactionId}, ${d.locationLabel} name, ${d.locationCapacity}, and ${d.amount}.`,
      starterSql: `-- Question 33: Join first, then filter using a column from ${d.locationTable}\n\n`,
      solutionSql: `SELECT t.${d.transactionId},\n       l.${d.locationName} AS ${d.locationLabel},\n       l.${d.locationCapacity},\n       t.${d.amount}\nFROM ${d.transactionTable} AS t\nJOIN ${d.locationTable} AS l\n  ON t.${d.transactionLocationId} = l.${d.locationId}\nWHERE l.${d.locationCapacity} > ${d.capacityThreshold}\nORDER BY t.${d.transactionId};`,
    },

    {
      id: "q34",
      title: "Build a Human-Readable Transaction List",
      topic: "CHAINED JOINS",
      prompt: `For ${d.transactionTable} with ${d.amount} at least ${d.amountThreshold}, display ${d.transactionId}, ${d.locationLabel} name, ${d.itemLabel} name, ${d.amount}, and ${d.status}. Connect ${d.transactionTable} to both ${d.locationTable} and ${d.itemTable}.`,
      starterSql: `-- Question 34: Chain two joins\n\n`,
      solutionSql: `SELECT t.${d.transactionId},\n       l.${d.locationName} AS ${d.locationLabel},\n       i.${d.itemName} AS ${d.itemLabel},\n       t.${d.amount},\n       t.${d.status}\nFROM ${d.transactionTable} AS t\nJOIN ${d.locationTable} AS l\n  ON t.${d.transactionLocationId} = l.${d.locationId}\nJOIN ${d.itemTable} AS i\n  ON t.${d.transactionItemId} = i.${d.itemId}\nWHERE t.${d.amount} >= ${d.amountThreshold}\nORDER BY t.${d.transactionId};`,
    },

    {
      id: "q35",
      title: "Extension: Filter Across Three Tables",
      topic: "CHALLENGE · MULTI-TABLE FILTER",
      prompt: `Return only ${d.plannedStatus} ${d.transactionTable} whose ${d.itemLabel} belongs to the '${d.categoryFilter}' category. Display ${d.locationLabel} name, ${d.itemLabel} name, ${d.amount}, and ${d.status}.`,
      starterSql: `-- Question 35: Join three tables and filter using two of them\n\n`,
      solutionSql: `SELECT l.${d.locationName} AS ${d.locationLabel},\n       i.${d.itemName} AS ${d.itemLabel},\n       t.${d.amount},\n       t.${d.status}\nFROM ${d.transactionTable} AS t\nJOIN ${d.locationTable} AS l\n  ON t.${d.transactionLocationId} = l.${d.locationId}\nJOIN ${d.itemTable} AS i\n  ON t.${d.transactionItemId} = i.${d.itemId}\nWHERE t.${d.status} = '${d.plannedStatus}'\n  AND i.${d.itemCategory} = '${d.categoryFilter}'\nORDER BY t.${d.transactionId};`,
    },

    {
      id: "q36",
      title: `Keep Every ${d.locationLabel}`,
      topic: "LEFT JOIN",
      prompt: `Create a roster showing every ${d.locationLabel}, its ${d.locationRegion}, and its ${d.leaderLabel}. A ${d.locationLabel} must remain in the result even when its region has no matching row in ${d.regionTable}.`,
      starterSql: `-- Question 36: Keep every left-side row\n\n`,
      solutionSql: `SELECT l.${d.locationName} AS ${d.locationLabel},\n       l.${d.locationRegion},\n       r.${d.leaderColumn} AS ${d.leaderLabel.replace(/ /g, "_")}\nFROM ${d.locationTable} AS l\nLEFT JOIN ${d.regionTable} AS r\n  ON l.${d.locationRegion} = r.${d.regionKey}\nORDER BY l.${d.locationId};`,
    },

    {
      id: "q37",
      title: `Extension: Find ${d.locationTable} Without a ${d.leaderLabel}`,
      topic: "CHALLENGE · LEFT JOIN · IS NULL",
      prompt: `Return only the ${d.locationTable} rows whose region has no matching ${d.leaderLabel} record.`,
      starterSql: `-- Question 37: Find unmatched left-side rows\n\n`,
      solutionSql: `SELECT l.${d.locationId},\n       l.${d.locationName},\n       l.${d.locationRegion}\nFROM ${d.locationTable} AS l\nLEFT JOIN ${d.regionTable} AS r\n  ON l.${d.locationRegion} = r.${d.regionKey}\nWHERE r.${d.leaderColumn} IS NULL\nORDER BY l.${d.locationId};`,
    },

    {
      id: "q38",
      title: `Classic SQL Pattern: Find ${d.itemTable} Never Used`,
      topic: "CHALLENGE · LEFT JOIN · MISSING RELATIONSHIP",
      prompt: `Return the ${d.itemId}, ${d.itemName}, and ${d.itemCategory} for every ${d.itemLabel} that does not appear in any ${d.transactionLabel}.`,
      starterSql: `-- Question 38: Find rows with no matching transaction\n\n`,
      solutionSql: `SELECT i.${d.itemId},\n       i.${d.itemName},\n       i.${d.itemCategory}\nFROM ${d.itemTable} AS i\nLEFT JOIN ${d.transactionTable} AS t\n  ON i.${d.itemId} = t.${d.transactionItemId}\nWHERE t.${d.transactionId} IS NULL;`,
    },

    {
      id: "q39",
      title: `Extension: Show Every ${d.locationLabel} and Its Planned ${d.transactionLabel}`,
      topic: "CHALLENGE · LEFT JOIN · ON vs WHERE",
      prompt: `Return every ${d.locationLabel} and its ${d.plannedStatus} ${d.transactionId} when one exists. ${d.locationTable} rows with no ${d.plannedStatus} ${d.transactionLabel} must still appear.`,
      starterSql: `-- Question 39: Put the right-table status test where unmatched left rows survive\n\n`,
      solutionSql: `SELECT l.${d.locationName} AS ${d.locationLabel},\n       t.${d.transactionId}\nFROM ${d.locationTable} AS l\nLEFT JOIN ${d.transactionTable} AS t\n  ON t.${d.transactionLocationId} = l.${d.locationId}\n AND t.${d.status} = '${d.plannedStatus}'\nORDER BY l.${d.locationId}, t.${d.transactionId};`,
    },

    {
      id: "q40",
      title: `Follow the ${d.relationLabel} Relationship`,
      topic: "SELF-JOIN",
      prompt: `Show each ${d.locationLabel} that has a ${d.relationLabel}, together with the ${d.relationLabel}'s name and capacity. Read ${d.locationTable} twice using two aliases.`,
      starterSql: `-- Question 40: Self-join ${d.locationTable}\n\n`,
      solutionSql: `SELECT l.${d.locationName} AS ${d.locationLabel},\n       target.${d.locationName} AS ${d.relationLabel.replace(/ /g, "_")},\n       target.${d.locationCapacity} AS target_capacity\nFROM ${d.locationTable} AS l\nJOIN ${d.locationTable} AS target\n  ON l.${d.relationId} = target.${d.locationId}\nORDER BY l.${d.locationId};`,
    },

    {
      id: "q41",
      title: "Real Challenge Question 1",
      topic: "CHALLENGE · COMPLETE OPERATIONS ROSTER",
      prompt: `Return every ${d.locationLabel} with its ${d.locationRegion}, ${d.leaderLabel}, and ${d.relationLabel} name when available. Every ${d.locationLabel} must remain even when either relationship is missing.`,
      starterSql: `-- Real Challenge Question 1\n-- Keep all locations while joining two optional relationships\n\n`,
      solutionSql: `SELECT l.${d.locationName} AS ${d.locationLabel},\n       l.${d.locationRegion},\n       r.${d.leaderColumn} AS ${d.leaderLabel.replace(/ /g, "_")},\n       target.${d.locationName} AS ${d.relationLabel.replace(/ /g, "_")}\nFROM ${d.locationTable} AS l\nLEFT JOIN ${d.regionTable} AS r\n  ON l.${d.locationRegion} = r.${d.regionKey}\nLEFT JOIN ${d.locationTable} AS target\n  ON l.${d.relationId} = target.${d.locationId}\nORDER BY l.${d.locationId};`,
    },

    {
      id: "q42",
      title: "Real Challenge Question 2",
      topic: "CHALLENGE · DEBUG A JOIN",
      prompt: `A student expects one result row per ${d.transactionLabel}, but the query below returns far too many rows because the pairing condition is missing. Repair it so each ${d.transactionLabel} is matched with the correct ${d.locationLabel} exactly once.`,
      starterSql: `-- Real Challenge Question 2\n-- This returns too many rows. Repair the join.\n\nSELECT *\nFROM ${d.transactionTable} AS t, ${d.locationTable} AS l;\n`,
      solutionSql: `SELECT t.${d.transactionId},\n       l.${d.locationName} AS ${d.locationLabel},\n       t.${d.amount},\n       t.${d.status}\nFROM ${d.transactionTable} AS t\nJOIN ${d.locationTable} AS l\n  ON t.${d.transactionLocationId} = l.${d.locationId}\nORDER BY t.${d.transactionId};`,
    },
  ];
}
