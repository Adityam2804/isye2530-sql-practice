import { day16Exercises } from '../data/day16.js';
import { Day16Runner } from '../python/day16Runner.js';
import { getAnswer, setAnswer, getSetting, setSetting } from '../storage/browserStorage.js';
import { handlePythonIndentation } from './pythonEditorKeys.js';
import '../styles/day16.css';

const esc = (value) =>
  String(value ?? '').replace(/[&<>"']/g, (ch) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  })[ch]);

function tableHtml(table) {
  const rows = table.values.length
    ? table.values.map((row) => `
        <tr>
          ${row.map((value) => `
            <td>${value === null ? '<em>NULL</em>' : `<code>${esc(typeof value === 'string' ? JSON.stringify(value) : value)}</code>`}</td>
          `).join('')}
        </tr>
      `).join('')
    : `<tr><td colspan="${table.columns.length}">0 rows</td></tr>`;

  return `
    <article class="day16-table-card">
      <h3>${esc(table.name)}</h3>
      <div class="day16-table-scroll">
        <table>
          <thead><tr>${table.columns.map((column) => `<th>${esc(column)}</th>`).join('')}</tr></thead>
          <tbody>${rows}</tbody>
        </table>
      </div>
    </article>
  `;
}

export function mountDay16Lab(root, dayOptions, onDay) {
  const savedId = getSetting('day16:question-id', 'q73');
  let index = Math.max(0, day16Exercises.findIndex((exercise) => exercise.id === savedId));
  let runner;
  let ready = false;
  let busy = false;
  let disposed = false;
  let generation = 0;
  let tables = [];

  const question = () => day16Exercises[index];
  const answerDomain = 'humanitarian-practice-v1';
  const code = () => getAnswer('day16', answerDomain, question().id, question().starter);
  const save = (value) => setAnswer('day16', answerDomain, question().id, value);
  const interpretationKey = () => `day16:interpretation:${question().id}`;

  function status(message, error = false) {
    const node = root.querySelector('#day16Status');
    if (!node) return;
    node.textContent = message;
    node.className = `status ${error ? 'error' : 'neutral'}`;
  }

  function controls() {
    root.querySelectorAll('[data-day16-run]').forEach((button) => {
      button.disabled = busy || !ready;
    });
  }

  function previews() {
    const container = root.querySelector('#day16Tables');
    if (!container) return;

    const wanted = new Set(question().tables);
    const selected = tables.filter((table) => wanted.has(table.name));

    container.innerHTML = selected.length
      ? selected.map(tableHtml).join('')
      : '<p class="day16-empty">No base table preview is available for this question.</p>';
  }

  function renderFigures(figures = []) {
    const panel = root.querySelector('#day16Charts');
    if (!panel) return;

    panel.innerHTML = figures.length
      ? figures.map((src, i) => `
          <figure class="day16-figure">
            <img src="${src}" alt="Matplotlib chart ${i + 1} generated by the student code">
          </figure>
        `).join('')
      : '<p class="day16-chart-placeholder">Run code that creates a Matplotlib figure to see it here.</p>';
  }

  async function previewSolution() {
    const q = question();
    const button = root.querySelector('#previewDay16Solution');
    const preview = root.querySelector('#day16SolutionPreview');
    const outputNode = root.querySelector('#day16ExpectedOutput');
    const chartNode = root.querySelector('#day16ExpectedCharts');

    if (!button || !preview || !outputNode) return;

    button.disabled = true;
    button.textContent = q.chart ? 'Generating expected output + plot…' : 'Generating expected output…';
    preview.hidden = false;
    outputNode.textContent = 'Running the reference solution in a fresh browser Python environment…';
    if (chartNode) chartNode.innerHTML = '';

    const solutionRunner = new Day16Runner();

    try {
      const initialized = await solutionRunner.request({ type: 'init' });
      if (initialized.error) throw new Error(initialized.error);

      const result = await solutionRunner.request({
        type: 'run',
        code: q.solution,
        chart: !!q.chart,
      });

      outputNode.textContent =
        ((result.output || '') + (result.error ? `\n${result.error}` : '')).trim()
        || 'Finished. No printed output.';

      if (chartNode) {
        chartNode.innerHTML = (result.figures || []).length
          ? result.figures.map((src, i) => `
              <figure class="day16-figure">
                <img src="${src}" alt="Expected Matplotlib chart ${i + 1} from the reference solution">
              </figure>
            `).join('')
          : '<p class="day16-chart-placeholder">The reference solution did not create a chart.</p>';
      }
    } catch (error) {
      outputNode.textContent = error.message || String(error);
    } finally {
      solutionRunner.stop();
      button.disabled = false;
      button.textContent = q.chart
        ? 'Generate expected output + plot'
        : 'Generate expected output';
    }
  }

  async function initialize() {
    const ticket = ++generation;
    runner?.stop();
    runner = new Day16Runner();
    ready = false;
    busy = true;
    controls();
    status('Loading the browser Python environment…');

    try {
      const result = await runner.request({ type: 'init' });
      if (disposed || ticket !== generation) return;
      if (result.error) throw new Error(result.error);
      tables = result.tables || [];
      ready = true;
      previews();
      status('Ready. Run the starter, complete the TODOs, and compare your output.');
    } catch (error) {
      if (!disposed && ticket === generation) {
        status(`${error.message} Reset Question to retry.`, true);
      }
    } finally {
      if (!disposed && ticket === generation) {
        busy = false;
        controls();
      }
    }
  }

  async function run(program) {
    if (busy || !ready) return;

    const ticket = generation;
    const editor = root.querySelector('#day16Editor');
    save(editor.value);
    busy = true;
    controls();
    status(question().chart
      ? 'Running… pandas and Matplotlib may take longer on their first browser load.'
      : 'Running… pandas may take longer on its first browser load.');

    try {
      const result = await runner.request({
        type: 'run',
        code: program,
        chart: !!question().chart,
      });

      if (disposed || ticket !== generation) return;

      root.querySelector('#day16Output').textContent =
        ((result.output || '') + (result.error ? `\n${result.error}` : '')).trim()
        || 'Finished. No printed output.';

      if (result.tables) {
        tables = result.tables;
        previews();
      }

      renderFigures(result.figures || []);

      status(
        result.error
          ? 'Python reported an error. Read the output, edit the code, and try again.'
          : 'Finished. The output and chart below came from your code.',
        !!result.error,
      );
    } catch (error) {
      if (!disposed && ticket === generation) {
        ready = false;
        status(error.message, true);
      }
    } finally {
      if (!disposed && ticket === generation) {
        busy = false;
        controls();
      }
    }
  }

  function render() {
    const q = question();
    const savedInterpretation = getSetting(interpretationKey(), '');

    root.innerHTML = `
      <header class="app-header">
        <div class="brand">
          <img src="/assets/rpi_logo.svg" alt="Rensselaer Polytechnic Institute" class="rpi-logo">
          <div class="brand-copy">
            <div class="brand-course">ISYE 2530</div>
            <div class="brand-title">SQL Practice</div>
          </div>
        </div>
        <div class="day-pill">Day 16 · Analysis with Data Frames</div>
      </header>

      <main class="shell day16-lab">
        <section class="toolbar">
          <div class="day-tabs" aria-label="Choose course day">
            ${dayOptions.map((day) => `
              <button data-lab-day="${esc(day.key)}" class="${day.key === 'day16' ? 'active' : ''}">
                ${esc(day.label)}
              </button>
            `).join('')}
          </div>
          <span class="database-note">Python + pandas + Matplotlib · Humanitarian Operations</span>
        </section>

        <section class="card question-nav">
          <div class="question-nav-top">
            <div>
              <span class="eyebrow">${esc(q.topic)}</span>
              <h1>Q${q.number}. ${esc(q.title)}</h1>
            </div>
            <div class="question-count">Question ${index + 1} of ${day16Exercises.length}</div>
          </div>

          <div class="pagination" aria-label="Choose question">
            ${day16Exercises.map((item, i) => `
              <button
                data-day16-question="${i}"
                class="${i === index ? 'current' : ''}"
                title="${esc(item.title)}"
                aria-label="Question ${item.number}: ${esc(item.title)}"
              >${item.number}</button>
            `).join('')}
          </div>

          <div class="question-content">
            <p class="question-prompt">${esc(q.prompt)}</p>

            <details class="question-tables">
              <summary>Show Tables for this question</summary>
              <p>These are the current base-table rows available to your Python analysis.</p>
              <div id="day16Tables" class="day16-table-grid"></div>
            </details>

            <details class="hint">
              <summary>Show Solution</summary>
              <p>${esc(q.explanation)}</p>
              <div class="day16-solution-actions">
                <button id="loadDay16Solution" class="outline">Load solution into editor</button>
                <button id="previewDay16Solution" class="outline">
                  ${q.chart ? 'Generate expected output + plot' : 'Generate expected output'}
                </button>
              </div>
              <pre class="solution-code"><code>${esc(q.solution)}</code></pre>
              <div id="day16SolutionPreview" class="day16-solution-preview" hidden>
                <h3>Expected Output</h3>
                <pre id="day16ExpectedOutput" class="python-output">Generate the reference output to compare with your result.</pre>
                ${q.chart ? `
                  <h3>Expected Plot</h3>
                  <div id="day16ExpectedCharts" class="day16-charts"></div>
                ` : ''}
              </div>
            </details>
          </div>

          <div class="question-buttons">
            <button id="day16Prev" class="outline" ${index === 0 ? 'disabled' : ''}>← Previous</button>
            <button id="day16Next" class="solid" ${index === day16Exercises.length - 1 ? 'disabled' : ''}>Next →</button>
          </div>
        </section>

        <section class="work-grid day16-work-grid">
          <section class="editor card">
            <div class="card-header">
              <strong>Python Editor</strong>
              <span class="shortcut">Ctrl/⌘ + Enter: Run · Tab / Shift+Tab: Indent</span>
            </div>
            <label class="sr-only" for="day16Editor">Python program</label>
            <textarea id="day16Editor" spellcheck="false">${esc(code())}</textarea>
            <div class="editor-footer">
              <button id="resetDay16" class="outline">Reset Question</button>
              <button id="stopDay16" class="outline danger">Stop</button>
              <button id="runDay16" class="run" data-day16-run>▶ Run Python</button>
            </div>
          </section>

          <section class="results card">
            <div class="card-header">
              <strong>Python Output</strong>
              <span>Printed DataFrames, Series, values, and errors</span>
            </div>
            <div id="day16Status" class="status" role="status" aria-live="polite"></div>
            <pre id="day16Output" class="python-output" tabindex="0" aria-label="Python output">Run the code to see its output.</pre>
          </section>
        </section>

        ${q.chart ? `
          <section class="card day16-chart-card">
            <div class="card-header">
              <strong>Chart Output</strong>
              <span>Matplotlib figure generated in your browser</span>
            </div>
            <div id="day16Charts" class="day16-charts">
              <p class="day16-chart-placeholder">Run code that creates a Matplotlib figure to see it here.</p>
            </div>
          </section>
        ` : ''}

        ${q.interpretation ? `
          <section class="card day16-interpretation">
            <label for="day16Interpretation"><strong>Your interpretation</strong></label>
            <p>Write one sentence that names the important pattern and the relevant values. Do not claim causation from a chart alone.</p>
            <textarea id="day16Interpretation" rows="4" placeholder="Write your one-sentence interpretation here…">${esc(savedInterpretation)}</textarea>
          </section>
        ` : ''}

        <p class="python-note">
          Code is saved in this browser per question. Reset Question restores the starter and a fresh relief.db.
          Python, pandas, and Matplotlib run locally in the browser; the first package load may take longer.
        </p>
      </main>

      <footer>Day 16 · Query → DataFrame → Analyze → Visualize → Interpret</footer>
    `;

    root.querySelectorAll('[data-lab-day]').forEach((button) => {
      button.onclick = () => onDay(button.dataset.labDay);
    });

    root.querySelectorAll('[data-day16-question]').forEach((button) => {
      button.onclick = () => choose(Number(button.dataset.day16Question));
    });

    root.querySelector('#day16Prev').onclick = () => choose(index - 1);
    root.querySelector('#day16Next').onclick = () => choose(index + 1);

    const editor = root.querySelector('#day16Editor');
    editor.oninput = () => save(editor.value);

    function runEditor() {
      const selection = editor.value.slice(editor.selectionStart, editor.selectionEnd).trim();
      run(selection || editor.value);
    }

    editor.onkeydown = (event) => {
      if ((event.ctrlKey || event.metaKey) && event.key === 'Enter') {
        event.preventDefault();
        runEditor();
        return;
      }

      if (handlePythonIndentation(event, editor)) {
        save(editor.value);
      }
    };

    root.querySelector('#runDay16').onclick = runEditor;

    root.querySelector('#stopDay16').onclick = () => {
      ++generation;
      runner?.stop();
      busy = false;
      ready = false;
      controls();
      status('Stopped. Reset Question to recreate the Python environment.');
    };

    root.querySelector('#resetDay16').onclick = () => {
      save(q.starter);
      editor.value = q.starter;
      root.querySelector('#day16Output').textContent = 'Question reset.';
      renderFigures([]);
      initialize();
    };

    root.querySelector('#loadDay16Solution').onclick = () => {
      editor.value = q.solution;
      save(editor.value);
      editor.focus();
    };

    root.querySelector('#previewDay16Solution').onclick = previewSolution;

    root.querySelector('#day16Interpretation')?.addEventListener('input', (event) => {
      setSetting(interpretationKey(), event.target.value);
    });

    initialize();
  }

  function choose(next) {
    if (next < 0 || next >= day16Exercises.length || next === index) return;

    const editor = root.querySelector('#day16Editor');
    if (editor) save(editor.value);

    ++generation;
    runner?.stop();
    index = next;
    setSetting('day16:question-id', question().id);
    render();
  }

  render();

  return () => {
    disposed = true;
    ++generation;
    runner?.stop();
  };
}
